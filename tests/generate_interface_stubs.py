"""Regenerate test-only default stubs from the matching OpenRGB ABI headers."""
import argparse
from pathlib import Path
import re

p = argparse.ArgumentParser()
p.add_argument("source", type=Path)
args = p.parse_args()
output = ["// Generated by generate_interface_stubs.py; test doubles only.", "#pragma once", "#include <OpenRGBPluginInterface.h>"]
for header, interface in [("OpenRGBPluginInterface.h", "OpenRGBPluginAPIInterface"),
                          ("RGBController/RGBControllerInterface.h", "RGBControllerInterface")]:
    content = (args.source / header).read_text()
    body = content.split("class " + interface, 1)[1].split("\n};", 1)[0]
    output += [f"struct Stub{interface} : {interface} {{"]
    methods = re.findall(r"virtual\s+(.+?)\s*=\s*0\s*;", body)
    for method in methods:
        method = method.strip()
        if "&" in method.split("(", 1)[0]:
            raise ValueError("Reference return needs an explicit test stub")
        result = "" if re.match(r"void\s", method) else "return {};"
        output.append(f"    {method} override {{{result}}}")
    output.append("};")
Path(__file__).with_name("interface_stubs.h").write_text("\n".join(output) + "\n", newline="\n")
